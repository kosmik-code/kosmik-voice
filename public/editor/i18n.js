export const CATALOG = { es, en };

let current = "es";

export function getLanguage() {
  return current;
}

/** Switch the language used by t(); unknown values are ignored. Returns the active language. */
export function setLanguage(lang) {
  if (LANGUAGES.includes(lang)) current = lang;
  return current;
}

/** Translated string for key with {param} placeholders filled. Missing in en -> es -> the key itself. */
export function t(key, params) {
  const s = CATALOG[current][key] ?? CATALOG.es[key] ?? key;
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : s;
}

/** Like t() but returns an array where params are kept as-is (e.g. DOM nodes to embed in text). */
export function parts(key, params = {}) {
  const s = CATALOG[current][key] ?? CATALOG.es[key] ?? key;
  const out = [];
  let last = 0;
  for (const m of s.matchAll(/\{(\w+)\}/g)) {
    if (!(m[1] in params)) continue;
    if (m.index > last) out.push(s.slice(last, m.index));
    out.push(params[m[1]]);
    last = m.index + m[0].length;
  }
  if (last < s.length) out.push(s.slice(last));
  return out;
}
